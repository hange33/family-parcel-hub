import 'package:flutter_test/flutter_test.dart';
import 'package:pickup_app/core/parser/trace_time.dart';

void main() {
  // 北京时间 2026-10-07 09:00:00
  final now = DateTime.parse('2026-10-07T09:00:00+08:00');
  String? n(Object? raw, {DateTime? at}) => normalizeTraceTime(raw, now: at ?? now);

  group('带年份', () {
    test('约定格式原样返回', () {
      expect(n('2026-10-06 14:23:05'), '2026-10-06 14:23:05');
    });

    test('缺秒补 :00', () {
      expect(n('2026-10-06 14:23'), '2026-10-06 14:23:00');
    });

    test('/ 和 . 分隔、个位数月日时', () {
      expect(n('2026/10/07 08:05'), '2026-10-07 08:05:00');
      expect(n('2026.10.07 08:05:09'), '2026-10-07 08:05:09');
      expect(n('2026/1/6 9:05'), '2026-01-06 09:05:00');
    });

    test('中文年月日', () {
      expect(n('2026年10月6日 14:23'), '2026-10-06 14:23:00');
      expect(n('2026年10月6日14时23分05秒'), '2026-10-06 14:23:05');
      expect(n('2026年10月6日 14时23分'), '2026-10-06 14:23:00');
    });

    test('多余空白、T 分隔、毫秒小数、全角冒号', () {
      expect(n('  2026-10-06   14:23:05  '), '2026-10-06 14:23:05');
      expect(n('2026-10-06T14:23:05'), '2026-10-06 14:23:05');
      expect(n('2026-10-06 14:23:05.123'), '2026-10-06 14:23:05');
      expect(n('2026-10-06 14：23'), '2026-10-06 14:23:00');
    });

    test('带时区的 ISO 8601 换算成北京时间', () {
      expect(n('2026-10-06T06:23:05Z'), '2026-10-06 14:23:05');
      expect(n('2026-10-06T14:23:05+08:00'), '2026-10-06 14:23:05');
      expect(n('2026-10-06T16:00:00Z'), '2026-10-07 00:00:00');
    });
  });

  group('缺年份', () {
    test('补当年', () {
      expect(n('10-06 14:23'), '2026-10-06 14:23:00');
      expect(n('10/06 14:23:05'), '2026-10-06 14:23:05');
      expect(n('10月6日 14:23'), '2026-10-06 14:23:00');
    });

    test('跨年：补当年后晚于当前时间则减一年', () {
      final newYear = DateTime.parse('2027-01-01T00:30:00+08:00');
      expect(n('12-31 23:50', at: newYear), '2026-12-31 23:50:00');
      expect(n('01-01 00:10', at: newYear), '2027-01-01 00:10:00');
    });

    test('比当前时间晚一天以内视为时钟误差，不减年', () {
      expect(n('10-07 10:00'), '2026-10-07 10:00:00');
      expect(n('10-09 10:00'), '2025-10-09 10:00:00');
    });

    test('当前时间按北京时间计算，与传入 DateTime 的时区无关', () {
      // UTC 2026-12-31 17:00 = 北京时间 2027-01-01 01:00
      final utc = DateTime.utc(2026, 12, 31, 17);
      expect(n('01-01 00:30', at: utc), '2027-01-01 00:30:00');
      expect(n('12-31 23:00', at: utc), '2026-12-31 23:00:00');
    });

    test('2 月 29 日：今年不存在就试上一年，上一年也不存在返回 null', () {
      final at = DateTime.parse('2029-03-01T09:00:00+08:00'); // 2029、2028 → 2028 是闰年
      expect(n('02-29 10:00', at: at), '2028-02-29 10:00:00');
      final at2 = DateTime.parse('2027-03-01T09:00:00+08:00'); // 2027、2026 都不是闰年
      expect(n('02-29 10:00', at: at2), isNull);
    });
  });

  group('时间戳', () {
    test('毫秒级数字和字符串', () {
      // 1791259800000 = 2026-10-06 04:10:00 UTC = 北京时间 12:10:00
      expect(n(1791259800000), '2026-10-06 12:10:00');
      expect(n('1791259800000'), '2026-10-06 12:10:00');
    });

    test('秒级数字和字符串', () {
      expect(n(1791259800), '2026-10-06 12:10:00');
      expect(n('1791259800'), '2026-10-06 12:10:00');
    });

    test('位数不对的数字返回 null', () {
      expect(n('12345'), isNull);
      expect(n(0), isNull);
      expect(n('179125980000'), isNull);
    });
  });

  group('解析不出返回 null', () {
    test('空、乱码、相对时间、只有日期或只有时间', () {
      for (final raw in [null, '', '   ', 'abc', '昨天 14:03', '刚刚', '2026-10-06', '14:23', '派件中']) {
        expect(n(raw), isNull, reason: '$raw');
      }
    });

    test('字段越界', () {
      for (final raw in ['2026-13-01 10:00', '2026-02-30 10:00', '2026-10-06 24:00', '2026-10-06 10:60', '2026-10-06 10:00:61']) {
        expect(n(raw), isNull, reason: raw);
      }
    });

    test('分钟后直接跟数字不当成秒', () {
      expect(n('2026-10-06 14:235'), isNull);
    });
  });
}
